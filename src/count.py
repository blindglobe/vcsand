def add_three_numbers(a, b, c):
    """
    This function takes three numbers as input and returns their sum.
    
    Parameters:
    a (int/float): The first number.
    b (int/float): The second number.
    c (int/float): The third number.
    
    Returns:
    int/float: The sum of the three numbers.
    """
    return a + b + c

# Example usage:
if __name__ == "__main__":
    result = add_three_numbers(1, 2, 3)
    print("The sum is:", result)  # Output: The sum is: 6